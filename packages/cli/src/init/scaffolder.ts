import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { EnvEntry } from "./envMatcher.js";
import { AlgoConfig } from "./algoDefaults.js";

export interface ProjectConfig {
  projectName: string;
  description: string;
  env: EnvEntry;
  algo: AlgoConfig;
  totalTimesteps: number;
  seed?: number;
}

/**
 * Scaffold an exterm project directory with:
 *  - exterm.yaml   (run configuration)
 *  - reward.py     (reward shaping stub ? editable via steering)
 *  - README.md     (quick-start instructions)
 */
export async function scaffoldProject(dir: string, config: ProjectConfig): Promise<void> {
  await mkdir(dir, { recursive: true });

  const hyperStr = Object.entries(config.algo.hyperparameters)
    .map(([k, v]) => `  ${k}: ${typeof v === "string" ? v : JSON.stringify(v)}`)
    .join("\n");

  const yaml = [
    `# exterm project ? generated by \`exterm init\``,
    `# Edit this file to change env, algorithm, or hyperparameters, then run: exterm train`,
    ``,
    `name: "${config.projectName}"`,
    `description: "${config.description.replace(/"/g, "'")}"`,
    ``,
    `environment:`,
    `  id: "${config.env.id}"`,
    `  # Action space: ${config.env.actionSpace}`,
    `  # Difficulty:   ${config.env.difficulty}`,
    `  # Reward type:  ${config.env.rewardDensity}`,
    ``,
    `training:`,
    `  algorithm: "${config.algo.algorithm}"`,
    `  policy: "${config.algo.policy}"`,
    `  total_timesteps: ${config.totalTimesteps}`,
    config.seed !== undefined ? `  seed: ${config.seed}` : null,
    `  # Rationale: ${config.algo.rationale}`,
    ``,
    `  hyperparameters:`,
    hyperStr || `    {}`,
  ]
    .filter((l) => l !== null)
    .join("\n");

  await writeFile(join(dir, "exterm.yaml"), yaml, "utf-8");

  // Reward shaping stub
  const isContinuous = config.env.actionSpace === "continuous";
  const rewardPy = [
    `"""`,
    `exterm reward shaping wrapper for ${config.env.name}.`,
    ``,
    `This file is managed by exterm ? every \`exterm steer\` command that modifies`,
    `the reward function will diff and patch this file, auto-checkpointing before`,
    `the change. Use \`exterm rollback\` to revert both code and model weights together.`,
    ``,
    `Shape the reward however you like ? just return a float from \`reward_fn\`.`,
    `The default below passes through the original environment reward unchanged.`,
    `"""`,
    `import gymnasium as gym`,
    `import numpy as np`,
    `from gymnasium import Wrapper`,
    ``,
    ``,
    `class RewardShapingWrapper(Wrapper):`,
    `    """Wraps ${config.env.id} to apply custom reward shaping."""`,
    ``,
    `    def step(self, action):`,
    `        obs, reward, terminated, truncated, info = self.env.step(action)`,
    `        shaped_reward = self.reward_fn(obs, action, reward, terminated, truncated, info)`,
    `        return obs, shaped_reward, terminated, truncated, info`,
    ``,
    `    def reward_fn(`,
    `        self,`,
    `        obs: np.ndarray,`,
    `        action${isContinuous ? ": np.ndarray" : ": int"},`,
    `        original_reward: float,`,
    `        terminated: bool,`,
    `        truncated: bool,`,
    `        info: dict,`,
    `    ) -> float:`,
    `        # ----- Edit below this line -----`,
    `        return original_reward`,
    `        # --------------------------------`,
    ``,
    ``,
    `def make_env(env_id: str = "${config.env.id}"):`,
    `    """Create the wrapped environment. Called by the exterm trainer."""`,
    `    env = gym.make(env_id)`,
    `    env = RewardShapingWrapper(env)`,
    `    return env`,
  ].join("\n");

  await writeFile(join(dir, "reward.py"), rewardPy, "utf-8");

  // README
  const readme = [
    `# ${config.projectName}`,
    ``,
    `> ${config.description}`,
    ``,
    `Generated by \`exterm init\` on ${new Date().toLocaleDateString()}.`,
    ``,
    `## Quick Start`,
    ``,
    `\`\`\`bash`,
    `# Train with defaults (${config.totalTimesteps.toLocaleString()} steps of ${config.algo.algorithm} on ${config.env.id})`,
    `exterm train`,
    ``,
    `# Override budget or algorithm`,
    `exterm train --steps 100000 --algo ${config.algo.algorithm}`,
    ``,
    `# Open the live dashboard`,
    `exterm dashboard`,
    `\`\`\``,
    ``,
    `## Agent Details`,
    ``,
    `| Field | Value |`,
    `|-------|-------|`,
    `| **Environment** | \`${config.env.id}\` |`,
    `| **Description** | ${config.env.description} |`,
    `| **Action Space** | ${config.env.actionSpace} |`,
    `| **Algorithm** | ${config.algo.algorithm} |`,
    `| **Default Budget** | ${config.totalTimesteps.toLocaleString()} steps |`,
    ``,
    `**Algorithm rationale:** ${config.algo.rationale}`,
    ``,
    `## Reward Shaping`,
    ``,
    `Edit \`reward.py\` to customise the reward function, or steer the agent at runtime:`,
    ``,
    `\`\`\`bash`,
    `exterm train   # then type natural language instructions while it runs`,
    `               # e.g. "penalise jerky actions" or "reward longer episodes more"`,
    `\`\`\``,
    ``,
    `Every steering command auto-checkpoints the model before applying ? use \`exterm rollback\` to undo.`,
  ].join("\n");

  await writeFile(join(dir, "README.md"), readme, "utf-8");
}
